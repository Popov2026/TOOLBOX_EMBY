std::string bannerText(const std::string &s) {
  std::string o;
  for (size_t i = 0; i < s.size();) {
    unsigned char c = static_cast<unsigned char>(s[i]);
    if (c < 0x80) { o += char(c); i++; continue; }
    // séquence UTF-8 : point de code
    uint32_t cp = 0; int n = 0;
    if ((c & 0xe0) == 0xc0) { cp = c & 0x1f; n = 1; }
    else if ((c & 0xf0) == 0xe0) { cp = c & 0x0f; n = 2; }
    else if ((c & 0xf8) == 0xf0) { cp = c & 0x07; n = 3; }
    i++;
    for (int k = 0; k < n && i < s.size(); k++, i++) cp = (cp << 6) | (static_cast<unsigned char>(s[i]) & 0x3f);
    const char *r = "?";
    switch (cp) {
      case 0xe0: case 0xe2: case 0xe4: r = "a"; break;
      case 0xe7: r = "c"; break;
      case 0xe8: case 0xe9: case 0xea: case 0xeb: r = "e"; break;
      case 0xee: case 0xef: r = "i"; break;
      case 0xf4: case 0xf6: r = "o"; break;
      case 0xf9: case 0xfb: case 0xfc: r = "u"; break;
      case 0xc0: case 0xc2: r = "A"; break;
      case 0xc7: r = "C"; break;
      case 0xc8: case 0xc9: case 0xca: r = "E"; break;
      case 0xab: case 0xbb: r = "\""; break;
      case 0xa0: case 0x202f: r = " "; break;
      case 0x2019: r = "'"; break;
      case 0x2026: r = "..."; break;
      case 0x2013: case 0x2014: r = "-"; break;
      default: break;
    }
    o += r;
  }
  return o;
}

std::vector<uint32_t> renderBanner(const std::string &utf8, int scale, int &w, int &h, uint32_t fg) {
  std::string t = bannerText(utf8);
  const int pad = 3;
  w = (int(t.size()) * 6 + 2 * pad) * scale;
  h = (7 + 2 * pad) * scale;
  std::vector<uint32_t> img(size_t(w) * h, 0xb0000000u);   // fond noir semi-transparent
  for (size_t k = 0; k < t.size(); k++) {
    int ch = static_cast<unsigned char>(t[k]);
    if (ch < 32 || ch > 126) ch = '?';
    const uint8_t *g = FONT[ch - 32];
    for (int cx = 0; cx < 5; cx++)
      for (int cy = 0; cy < 8; cy++) {
        if (!((g[cx] >> cy) & 1)) continue;
        int x0 = (pad + int(k) * 6 + cx) * scale, y0 = (pad + cy) * scale;
        for (int yy = 0; yy < scale; yy++)
          for (int xx = 0; xx < scale; xx++)
            if (y0 + yy < h) img[size_t(y0 + yy) * w + x0 + xx] = fg;
      }
  }
  return img;
}

